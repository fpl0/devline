using Microsoft.EntityFrameworkCore;
using TaskApi;
var builder = WebApplication.CreateBuilder(args);
builder.Services.AddControllers();
builder.Services.AddProblemDetails();
Directory.CreateDirectory("storage");
builder.Services.AddDbContext<TaskDatabase>(o => o.UseSqlite(builder.Configuration.GetConnectionString("Issues") ?? "Data Source=storage/issues.db"));
var app = builder.Build();
app.UseExceptionHandler();
await using (var scope = app.Services.CreateAsyncScope()) await scope.ServiceProvider.GetRequiredService<TaskDatabase>().Database.EnsureCreatedAsync();
app.MapControllers();
app.MapGet("/", () => Results.Ok(new { name = "Issue Desk", issues = "/api/issues", health = "/health/ready" }));
app.MapGet("/health/ready", async (TaskDatabase database, CancellationToken cancellation) => await database.Database.CanConnectAsync(cancellation) ? Results.Ok(new { status = "ready", database = "sqlite" }) : Results.StatusCode(503));
await app.RunAsync();
