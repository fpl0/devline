using Microsoft.AspNetCore.Authentication.Cookies;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using TaskBoard.Data;
using TaskBoard.Services;
var builder = WebApplication.CreateBuilder(args);
builder.Services.AddControllersWithViews(o => o.Filters.Add(new AutoValidateAntiforgeryTokenAttribute()));
builder.Services.AddAuthentication(CookieAuthenticationDefaults.AuthenticationScheme).AddCookie(o => { o.LoginPath = "/account/login"; o.AccessDeniedPath = "/account/denied"; o.Cookie.Name = "purchase-desk"; o.ExpireTimeSpan = TimeSpan.FromHours(2); });
builder.Services.AddAuthorization();
Directory.CreateDirectory("storage");
builder.Services.AddDbContext<PurchaseDatabase>(o => o.UseSqlite(builder.Configuration.GetConnectionString("Purchases") ?? "Data Source=storage/purchases.db"));
builder.Services.AddScoped<PurchaseService>();
var app = builder.Build();
await using (var scope = app.Services.CreateAsyncScope()) await scope.ServiceProvider.GetRequiredService<PurchaseDatabase>().Database.EnsureCreatedAsync();
app.UseExceptionHandler("/error");
app.UseStaticFiles();
app.UseRouting();
app.UseAuthentication();
app.UseAuthorization();
app.MapControllers();
app.MapGet("/health/ready", async (PurchaseDatabase db) => await db.Database.CanConnectAsync() ? Results.Ok(new { status = "ready" }) : Results.StatusCode(503));
app.MapGet("/error", () => Results.Problem("The request could not be completed. Check the local application log."));
await app.RunAsync();
