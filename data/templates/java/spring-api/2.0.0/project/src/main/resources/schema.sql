CREATE TABLE IF NOT EXISTS issues (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(160) NOT NULL, description VARCHAR(4000) NOT NULL,
 priority VARCHAR(12) NOT NULL, status VARCHAR(16) NOT NULL, version BIGINT NOT NULL,
 created_at VARCHAR(40) NOT NULL, updated_at VARCHAR(40) NOT NULL
);
CREATE INDEX IF NOT EXISTS issues_status ON issues(status,id);
CREATE TABLE IF NOT EXISTS issue_events (
 issue_id BIGINT NOT NULL REFERENCES issues(id),version BIGINT NOT NULL,
 action VARCHAR(100) NOT NULL,happened_at VARCHAR(40) NOT NULL,PRIMARY KEY(issue_id,version)
);
