CREATE TABLE IF NOT EXISTS board_task (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner text NOT NULL,
    title varchar(120) NOT NULL CHECK (length(btrim(title)) > 0),
    completed boolean NOT NULL DEFAULT false,
    published boolean NOT NULL DEFAULT false,
    recorded boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS board_task_owner_id ON board_task (owner, id);
CREATE INDEX IF NOT EXISTS board_task_pending_completion ON board_task (id) WHERE completed AND NOT published;
