CREATE TABLE IF NOT EXISTS purchases (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,title VARCHAR(160) NOT NULL,reason VARCHAR(2000) NOT NULL,
 amount_cents BIGINT NOT NULL,requested_by VARCHAR(100) NOT NULL,status VARCHAR(12) NOT NULL,version BIGINT NOT NULL,
 decided_by VARCHAR(100),decision_note VARCHAR(500),created_at VARCHAR(40) NOT NULL
);
CREATE TABLE IF NOT EXISTS purchase_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,purchase_id BIGINT NOT NULL REFERENCES purchases(id),
 actor VARCHAR(100) NOT NULL,action VARCHAR(20) NOT NULL,note VARCHAR(2000) NOT NULL,happened_at VARCHAR(40) NOT NULL
);
